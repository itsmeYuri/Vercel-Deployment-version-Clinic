CREATE TABLE IF NOT EXISTS lab_packages (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(160) NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  price NUMERIC(10,2) NOT NULL CHECK (price >= 0),
  status VARCHAR(20) NOT NULL DEFAULT 'Draft' CHECK (status IN ('Draft', 'Published')),
  display_order INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS lab_package_tests (
  package_id INTEGER NOT NULL REFERENCES lab_packages(id) ON DELETE CASCADE,
  test_id INTEGER NOT NULL REFERENCES test_definitions(id) ON DELETE RESTRICT,
  PRIMARY KEY (package_id, test_id)
);
CREATE INDEX IF NOT EXISTS idx_lab_packages_public ON lab_packages(status, display_order, id);
CREATE INDEX IF NOT EXISTS idx_lab_package_tests_test ON lab_package_tests(test_id);
ALTER TABLE lab_packages ENABLE ROW LEVEL SECURITY;
ALTER TABLE lab_package_tests ENABLE ROW LEVEL SECURITY;
